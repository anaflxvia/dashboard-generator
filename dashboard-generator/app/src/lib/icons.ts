export function resolveIcon(name: string | undefined, label: string): LucideIcon {
  const key = name?.trim().toLowerCase()
  if (key && ICONS[key]) return ICONS[key]
  for (const [re, icon] of KEYWORDS) {
    if (re.test(label)) return ICONS[icon]
  }
  return BarChart3
}
